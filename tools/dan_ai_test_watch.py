#!/usr/bin/env python3
"""Watch DAN Terminal source changes, debounce, then run local quick tests.

Requires Linux inotify-tools. Never executes commands generated by an AI.
Optional --publish-failures posts only sanitized failure reports to GitHub.
"""
import argparse
from pathlib import Path
import selectors
import shutil
import subprocess
import sys
import time

ALLOWED = {".kt", ".kts", ".java", ".xml", ".toml", ".properties", ".gradle"}

def monitors(root):
    source = []
    for parent in (root / "app", root / "core", root / "feature"):
        src = parent / "src"
        if src.is_dir():
            source.append(src)
        if parent.is_dir():
            source.extend(p for p in sorted(parent.glob("*/src")) if p.is_dir())
    gradle = root / "gradle"
    if gradle.is_dir():
        source.append(gradle)
    return source

def relevant(name, root):
    try:
        path = Path(name).resolve().relative_to(root)
    except ValueError:
        return False
    if path.suffix not in ALLOWED:
        return False
    if any(part in ("build", ".gradle", ".git", "generated", ".idea")
           for part in path.parts):
        return False
    if path.name.startswith(".") or path.name.endswith("~"):
        return False
    return True

def watcher(root, debounce, publish_failures):
    if not shutil.which("inotifywait"):
        raise RuntimeError("inotifywait missing. Install package: sudo pacman -S inotify-tools")
    agent = root / "tools" / "dan_ai_test_agent.py"
    if not agent.is_file():
        raise RuntimeError("Test agent missing: " + str(agent))
    roots = monitors(root)
    if not roots:
        raise RuntimeError("No Android source directories found")
    # Monitor source trees recursively. Also monitor the repository top level
    # non-recursively for root build and Gradle config file changes.
    commands = [
        ["inotifywait", "-m", "-q", "-r", "-e",
         "close_write,moved_to,create,delete", "--format", "%w%f",
         *map(str, roots)],
        ["inotifywait", "-m", "-q", "-e",
         "close_write,moved_to,create,delete", "--format", "%w%f",
         str(root)],
    ]
    sel = selectors.DefaultSelector()
    processes = []
    for command in commands:
        process = subprocess.Popen(command, stdout=subprocess.PIPE,
                                   stderr=subprocess.PIPE, text=True, bufsize=1)
        processes.append(process)
        sel.register(process.stdout, selectors.EVENT_READ, process)

    print("DAN AI watcher ready: source edits trigger quick tests after " +
          str(debounce) + "s quiet period", flush=True)
    print("GitHub failure reporting: " + ("enabled" if publish_failures else "disabled"),
          flush=True)
    pending_at = None
    try:
        while True:
            if any(p.poll() is not None for p in processes):
                raise RuntimeError("inotifywait stopped; restart the watcher")
            now = time.monotonic()
            timeout = min(2.0, max(0.0, pending_at - now)) if pending_at else 2.0
            events = sel.select(timeout)
            for key, _ in events:
                line = key.fileobj.readline()
                if not line:
                    raise RuntimeError("inotifywait pipe unexpectedly closed")
                if relevant(line.strip(), root):
                    pending_at = time.monotonic() + debounce
            if pending_at is not None and time.monotonic() >= pending_at:
                pending_at = None
                print("DAN-AI change detected: running local quick gate", flush=True)
                cmd = [sys.executable, str(agent), "--repo-path", str(root),
                       "--mode", "quick"]
                if publish_failures:
                    cmd.append("--publish-on-failure")
                # Finish one test cycle before processing buffered events.
                # Changes during a Gradle run will trigger another cycle.
                result = subprocess.run(cmd, cwd=root, check=False)
                print("DAN-AI quick gate exit: " + str(result.returncode), flush=True)
    finally:
        sel.close()
        for process in processes:
            process.terminate()
            try:
                process.wait(timeout=3)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait()

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-path", type=Path,
                        default=Path("/home/dan/dan-terminal-m3-verify"))
    parser.add_argument("--debounce", type=float, default=10.0)
    parser.add_argument("--publish-failures", action="store_true")
    args = parser.parse_args()
    if not 1 <= args.debounce <= 300:
        parser.error("debounce must be between 1 and 300 seconds")
    try:
        return watcher(args.repo_path.expanduser().resolve(),
                       args.debounce, args.publish_failures)
    except (OSError, RuntimeError) as error:
        print("DAN-AI watcher error: " + str(error), file=sys.stderr)
        return 1

if __name__ == "__main__":
    sys.exit(main())
